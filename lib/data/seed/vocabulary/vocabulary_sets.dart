// ─── Vocabulary sets ──────────────────────────────────────────────────────────
//
// Phrase-level study sets that sit beside the A–Z dictionary: idioms, phrasal
// verbs, confused words, one-word substitutions, and prefixes & suffixes. Each
// entry has its meaning in English, Odia and Hindi plus an English example.

class VocabSetEntry {
  /// The idiom, phrasal verb, word pair, one word, or prefix/suffix.
  final String term;
  final String meaningEn;
  final String meaningOr;
  final String meaningHi;
  final String example;

  const VocabSetEntry({
    required this.term,
    required this.meaningEn,
    required this.meaningOr,
    required this.meaningHi,
    required this.example,
  });

  String regionalMeaning(RegionalLanguage lang) => switch (lang) {
    RegionalLanguage.english => meaningEn,
    RegionalLanguage.odia => meaningOr,
    RegionalLanguage.hindi => meaningHi,
  };
}

class VocabSet {
  final String id;
  final String title;
  final String subtitle;
  final IconData icon;
  final List<VocabSetEntry> entries;

  const VocabSet({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.icon,
    required this.entries,
  });
}

VocabSet? vocabSetById(String id) {
  for (final s in vocabularySets) {
    if (s.id == id) return s;
  }
  return null;
}

